    def generate_validation_report(self, validation_results: Dict[str, ValidationMetrics],
                                 output_path: str) -> None:
        """Generate comprehensive validation report."""
        
        output_path = Path(output_path)
        output_path.parent.mkdir(parents=True, exist_ok=True)
        
        # Calculate overall validation score
        overall_score = np.mean([result.validation_score for result in validation_results.values()])
        
        # Count pass/warning/fail
        status_counts = {}
        for result in validation_results.values():
            status = result.validation_status
            status_counts[status] = status_counts.get(status, 0) + 1
        
        # Create report
        report = {
            'validation_summary': {
                'overall_score': overall_score,
                'overall_status': 'PASS' if overall_score >= 0.8 else 'WARNING' if overall_score >= 0.6 else 'FAIL',
                'total_variables': len(validation_results),
                'status_breakdown': status_counts,
                'generation_timestamp': datetime.now().isoformat()
            },
            'variable_results': {}
        }
        
        # Add detailed results for each variable
        for var_name, result in validation_results.items():
            report['variable_results'][var_name] = asdict(result)
        
        # Save report
        with open(output_path, 'w') as f:
            json.dump(report, f, indent=2, default=str)
        
        logger.info(f"Validation report saved to {output_path}")
        
        # Print summary
        print(f"\n🔍 DIGITAL TWIN VALIDATION REPORT")
        print(f"=" * 50)
        print(f"Overall Score: {overall_score:.3f}")
        print(f"Overall Status: {report['validation_summary']['overall_status']}")
        print(f"Variables Tested: {len(validation_results)}")
        print(f"Status Breakdown: {status_counts}")
        
        print(f"\n📊 Variable Results:")
        for var_name, result in validation_results.items():
            print(f"  {var_name:20s}: {result.validation_status:8s} (Score: {result.validation_score:.3f})")
    
