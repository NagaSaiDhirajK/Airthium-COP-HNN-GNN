    def validate_variable(self, real_values: np.ndarray, synthetic_values: np.ndarray,
                         variable_name: str) -> ValidationMetrics:
        """Validate a single variable between real and synthetic data."""
        
        # Basic statistics
        real_stats = {
            'mean': np.mean(real_values),
            'std': np.std(real_values),
            'min': np.min(real_values),
            'max': np.max(real_values),
            'median': np.median(real_values),
            'q25': np.percentile(real_values, 25),
            'q75': np.percentile(real_values, 75)
        }
        
        synthetic_stats = {
            'mean': np.mean(synthetic_values),
            'std': np.std(synthetic_values),
            'min': np.min(synthetic_values),
            'max': np.max(synthetic_values),
            'median': np.median(synthetic_values),
            'q25': np.percentile(synthetic_values, 25),
            'q75': np.percentile(synthetic_values, 75)
        }
        
        # Statistical tests
        ks_stat, ks_p = stats.ks_2samp(real_values, synthetic_values)
        
        # Anderson-Darling test (if samples are large enough)
        try:
            ad_stat = stats.anderson_ksamp([real_values, synthetic_values])[0]
        except:
            ad_stat = np.nan
        
        # Chi-square test (for binned data)
        try:
            # Create bins and compare histograms
            bins = np.linspace(min(np.min(real_values), np.min(synthetic_values)),
                             max(np.max(real_values), np.max(synthetic_values)), 20)
            real_hist, _ = np.histogram(real_values, bins=bins)
            synthetic_hist, _ = np.histogram(synthetic_values, bins=bins)
            
            # Avoid zero counts
            real_hist = real_hist + 1
            synthetic_hist = synthetic_hist + 1
            
            chi2_stat, chi2_p = stats.chisquare(synthetic_hist, real_hist)
        except:
            chi2_stat, chi2_p = np.nan, np.nan
        
        # Error metrics
        if len(real_values) == len(synthetic_values):
            mae = np.mean(np.abs(real_values - synthetic_values))
            rmse = np.sqrt(np.mean((real_values - synthetic_values)**2))
            correlation = np.corrcoef(real_values, synthetic_values)[0, 1]
            r_squared = correlation**2
        else:
            # Interpolate to same length for comparison
            min_len = min(len(real_values), len(synthetic_values))
            real_interp = np.interp(np.linspace(0, 1, min_len), 
                                  np.linspace(0, 1, len(real_values)), real_values)
            synthetic_interp = np.interp(np.linspace(0, 1, min_len),
                                       np.linspace(0, 1, len(synthetic_values)), synthetic_values)
            
            mae = np.mean(np.abs(real_interp - synthetic_interp))
            rmse = np.sqrt(np.mean((real_interp - synthetic_interp)**2))
            correlation = np.corrcoef(real_interp, synthetic_interp)[0, 1]
            r_squared = correlation**2
        
        # Physics validation (simplified)
        energy_conservation_error = abs(np.mean(real_values) - np.mean(synthetic_values)) / np.mean(real_values)
        mass_conservation_error = abs(np.std(real_values) - np.std(synthetic_values)) / np.std(real_values)
        entropy_generation_check = np.mean(synthetic_values) >= np.mean(real_values)  # Simplified check
        
        # Calculate validation score
        validation_score = self._calculate_validation_score(
            variable_name, mae, rmse, correlation, ks_p
        )
        
        # Determine validation status
        if validation_score >= 0.8:
            validation_status = 'PASS'
        elif validation_score >= 0.6:
            validation_status = 'WARNING'
        else:
            validation_status = 'FAIL'
        
        return ValidationMetrics(
            metric_name=variable_name,
            real_data_stats=real_stats,
            synthetic_data_stats=synthetic_stats,
            ks_test_statistic=ks_stat,
            ks_test_p_value=ks_p,
            anderson_darling_statistic=ad_stat,
            chi_square_statistic=chi2_stat,
            chi_square_p_value=chi2_p,
            mean_absolute_error=mae,
            root_mean_square_error=rmse,
            correlation_coefficient=correlation,
            coefficient_of_determination=r_squared,
            energy_conservation_error=energy_conservation_error,
            mass_conservation_error=mass_conservation_error,
            entropy_generation_check=entropy_generation_check,
            validation_score=validation_score,
            validation_status=validation_status
        )
    
