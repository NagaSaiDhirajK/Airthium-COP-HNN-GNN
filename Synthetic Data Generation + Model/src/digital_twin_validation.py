    def _calculate_validation_score(self, variable_name: str, mae: float, 
                                  rmse: float, correlation: float, ks_p_value: float) -> float:
        """Calculate overall validation score for a variable."""
        
        # Get thresholds for this variable type
        var_type = self._get_variable_type(variable_name)
        thresholds = self.validation_thresholds.get(var_type, self.validation_thresholds['temperature'])
        
        # Score components (0-1 each)
        mae_score = max(0, 1 - mae / thresholds['max_mae'])
        rmse_score = max(0, 1 - rmse / thresholds['max_rmse'])
        corr_score = max(0, (correlation - 0.5) / 0.5)  # Scale from 0.5-1.0 to 0-1
        ks_score = min(1, ks_p_value / self.significance_level)  # Higher p-value is better
        
        # Weighted average
        weights = [0.3, 0.3, 0.3, 0.1]  # MAE, RMSE, Correlation, KS test
        scores = [mae_score, rmse_score, corr_score, ks_score]
        
        return np.average(scores, weights=weights)
    
    def _get_variable_type(self, variable_name: str) -> str:
        """Determine variable type for threshold lookup."""
        
        if 'temp' in variable_name.lower():
            return 'temperature'
        elif 'pressure' in variable_name.lower():
            return 'pressure'
        elif 'flow' in variable_name.lower():
            return 'flow_rate'
        elif 'power' in variable_name.lower():
            return 'power'
        elif 'cop' in variable_name.lower():
            return 'cop'
        else:
            return 'temperature'  # Default
    
