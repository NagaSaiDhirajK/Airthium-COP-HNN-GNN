    def _calculate_overall_summary(self, model_results: Dict[str, Any]) -> Dict[str, Any]:
        """Calculate overall summary statistics."""
        
        model_scores = [result.get('model_score', 0.0) for result in model_results.values() 
                       if isinstance(result.get('model_score'), (int, float))]
        
        status_counts = {}
        for result in model_results.values():
            status = result.get('model_status', 'UNKNOWN')
            status_counts[status] = status_counts.get(status, 0) + 1
        
        return {
            'overall_score': np.mean(model_scores) if model_scores else 0.0,
            'models_tested': len(model_results),
            'models_passed': status_counts.get('PASS', 0),
            'models_warning': status_counts.get('WARNING', 0),
            'models_failed': status_counts.get('FAIL', 0) + status_counts.get('ERROR', 0),
            'status_breakdown': status_counts,
            'best_performing_model': max(model_results.keys(), 
                                       key=lambda k: model_results[k].get('model_score', 0.0)) if model_results else None,
            'worst_performing_model': min(model_results.keys(), 
                                        key=lambda k: model_results[k].get('model_score', 0.0)) if model_results else None
        }
    
